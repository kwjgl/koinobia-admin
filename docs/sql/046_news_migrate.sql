### 삼위일체 하나님을 생각하며

세 앱을 구상하면서 기능만큼 중요하게 생각한 것은 그 기능들이 담고 있는 신앙적 의미였습니다. 여러 신앙고백과 교리문답을 읽고 공부하면서, 그리스도인의 신앙과 삶이 삼위일체 하나님께 깊이 연결되어 있음을 거듭 생각하게 되었습니다.

기도는 단순히 소원을 나열하는 일이 아닙니다. 성령 안에서, 그리스도를 통하여, 성부 하나님께 나아가는 일입니다. 우리의 기도보다 앞서 계시는 하나님의 은혜를 기억하며 그분과 교제하는 일입니다.

말씀을 배우는 일 역시 단순히 종교적 지식을 쌓는 데 그치지 않습니다. 성경을 통해 자신을 계시하시는 삼위일체 하나님을 알아 가고, 그 말씀 앞에서 묻고 생각하며 삶을 돌아보는 일입니다.

삶을 계획하는 일도 마찬가지입니다. 우리는 한 해의 목표를 정하고, 시간을 나누어 쓰며, 무언가를 이루기 위해 노력합니다. 그러나 모든 일이 우리의 뜻대로 이루어지는 것은 아닙니다. 하나님께 지혜와 인도하심을 구하며 계획하되, 그 결과까지 자신의 손에 붙들어 두려 하지는 않아야 합니다.

이러한 묵상이 앱의 구조와 작은 기능에도 자연스럽게 스며들기를 바랐습니다. 기술을 통해 신앙을 설명하려는 것이 아니라, **앱을 사용하는 동안에도 우리가 누구 앞에서 살아가는지를 잊지 않도록** 하고 싶었습니다.

### 즉시 답을 얻는 시대에 기다림을 배우며

우리는 무엇이든 빠르게 얻을 수 있는 시대에 살고 있습니다. 궁금한 것이 생기면 검색하고, 이제는 AI에게 물어 몇 초 만에 그럴듯한 답을 얻습니다. 편리하고 유익한 변화입니다.

그러나 모든 중요한 일이 그렇게 이루어지지는 않습니다.

어떤 기도는 오랜 시간 응답을 기다려야 합니다. 때로는 자신이 바라던 응답을 내려놓아야 할 수도 있습니다. 말씀을 읽으며 생긴 질문도 당장 풀리지 않을 수 있습니다. 몇 달, 몇 년이 지난 뒤에야 예전에 품었던 질문을 새로운 눈으로 이해하게 되기도 합니다.

우리의 삶도 그렇습니다. 계획을 세웠다고 곧바로 달라지지 않으며, 하루를 제대로 보내지 못했다고 모든 계획이 실패하는 것도 아닙니다.

그래서 세 앱은 서로 다른 방식으로 **인내와 기다림**을 돕도록 구상했습니다. 코이데는 기도제목을 오래 품고, 변화와 응답을 돌아보게 합니다. 디다코는 답하지 못한 질문도 그대로 간직하고, 언젠가 찾아온 발견과 연결할 수 있게 합니다. 탈리오는 한 해와 분기의 방향을 정하고 하루와 한 주의 걸음을 살피되, 하루의 성취에 지나치게 매이지 않도록 돕습니다.

기도한 날을 기록할 수는 있지만, 기도하지 못한 날 때문에 지나온 시간이 사라지지는 않습니다. 질문에 답하지 못했다고 실패한 것도 아닙니다. 계획을 모두 이루지 못했더라도 다시 시작할 수 있습니다.

그리스도인의 삶에서 중요한 것은 언제나 즉각적인 성취만은 아니라고 생각합니다. 인내하며 기다리고, 소망하며 사랑하고, 넘어지더라도 다시 걸어가는 시간 역시 소중합니다.

### 앱은 삶을 대신할 수 없습니다

좋은 노트나 필기구가 있다고 해서 저절로 기도하게 되거나 말씀을 깊이 이해하게 되는 것은 아닙니다. 잘 만든 앱도 마찬가지입니다. 앱은 기도를 대신할 수 없고, 말씀을 깨닫게 하는 주체가 될 수도 없습니다. 우리의 삶을 대신 살아 주지도 못합니다.

하지만 좋은 도구는 불필요한 수고를 덜어 줄 수 있습니다.

기도제목을 다시 작성하는 데 쓰던 시간을 기도하는 데 쓸 수 있습니다. 흩어진 메모를 찾는 대신 오래전 품었던 질문을 다시 생각할 수 있습니다. 복잡한 계획표를 관리하는 데 매달리기보다 오늘 해야 할 작은 일에 집중할 수 있습니다.

코이노비아가 바라는 것은 바로 그런 모습입니다.

