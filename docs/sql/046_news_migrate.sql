drop function if exists public.admin_news_save(bigint, text, text, text, text, date, text);
create or replace function public.admin_news_save(p_id bigint, p_title text, p_tag text, p_summary text, p_body text, p_date date, p_status text,
  p_kind text default '공지', p_app text default '', p_source text default '') returns jsonb
language plpgsql security definer set search_path = '' as $$
declare ti text := pg_catalog.btrim(coalesce(p_title, '')); tg text := pg_catalog.btrim(coalesce(p_tag, ''));
        su text := pg_catalog.btrim(coalesce(p_summary, '')); bo text := pg_catalog.btrim(pg_catalog.replace(pg_catalog.replace(coalesce(p_body, ''), E'\r\n', E'\n'), E'\r', E'\n'), E' \n\t');
        dt date := coalesce(p_date, public.koide_today()); sid bigint; kd text := coalesce(p_kind, '공지');
        ap text := pg_catalog.btrim(coalesce(p_app, '')); src jsonb;
begin
  perform public.admin_gate();
  if p_status is null or p_status not in ('임시', '올림') then raise exception 'bad: 상태는 임시 또는 올림이에요.'; end if;
  if kd not in ('공지', '개발 노트') then raise exception 'bad: 종류는 공지 또는 개발 노트예요.'; end if;
  if pg_catalog.char_length(ti) not between 1 and 100 then raise exception 'bad: 제목은 1~100글자로 써 주세요.'; end if;
  if pg_catalog.char_length(tg) > 20 then raise exception 'bad: 꼬리표는 20글자 이하로 써 주세요.'; end if;
  if pg_catalog.char_length(su) > 200 then raise exception 'bad: 요약은 200글자 이하로 써 주세요.'; end if;
  if pg_catalog.char_length(bo) not between 1 and 20000 then raise exception 'bad: 본문은 1~20000글자로 써 주세요.'; end if;
  if pg_catalog.char_length(ap) > 12 then raise exception 'bad: 앱 이름은 12글자 이하로 써 주세요.'; end if;
  if kd = '공지' then ap := ''; end if;
  select coalesce(pg_catalog.jsonb_agg(l.t order by l.n), '[]'::jsonb) into src
    from (select pg_catalog.btrim(x.t) as t, x.n from pg_catalog.regexp_split_to_table(coalesce(p_source, ''), E'\n') with ordinality as x(t, n)) l where l.t <> '';
  if pg_catalog.jsonb_array_length(src) > 8 or exists (select 1 from pg_catalog.jsonb_array_elements_text(src) e where pg_catalog.char_length(e) > 200) then
    raise exception 'bad: 참고 자료는 8줄 이하, 줄마다 200글자 이하로 써 주세요.';
  end if;
  if dt < date '2020-01-01' or dt > public.koide_today() + 3650 then raise exception 'bad: 날짜를 다시 확인해 주세요.'; end if;
  if p_id is null then
    insert into public.news_post(title, tag, summary, body, post_date, status, kind, app, source) values (ti, tg, su, bo, dt, p_status, kd, ap, src) returning id into sid;
  else
    update public.news_post set title = ti, tag = tg, summary = su, body = bo, post_date = dt, status = p_status, kind = kd, app = ap, source = src, updated_at = now()
      where id = p_id returning id into sid;
    if sid is null then raise exception 'bad: 글을 찾지 못했어요.'; end if;
  end if;
  perform public.admin_log_put('news-save', sid::text || '=' || p_status);
  return public.admin_news_list() || pg_catalog.jsonb_build_object('saved', sid);
end $$;

